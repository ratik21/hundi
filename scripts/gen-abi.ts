/** Writes the vault ABI from forge output. Usage: bun scripts/gen-abi.ts */
import { readFile, writeFile } from "node:fs/promises";

const artifact = JSON.parse(
  await readFile("contracts/out/HundiVault.sol/HundiVault.json", "utf8")
);
await writeFile(
  "packages/wallet/src/abi.generated.ts",
  `// Generated by scripts/gen-abi.ts from forge out/. Do not edit.
export const vaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`
);
